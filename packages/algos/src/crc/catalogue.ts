/**
 * Parameters transcribed from Greg Cook's "Catalogue of parametrised CRC algorithm
 * definitions" (the RevEng catalogue), which is the reference every other CRC list
 * derives from.
 *
 * Every entry carries the catalogue's published `check` value — the CRC of the ASCII
 * bytes "123456789" — and `tests/crc.test.ts` verifies it for all of them. That is
 * what makes it safe to transcribe this many constants by hand: getting a polynomial
 * digit or a reflection flag wrong cannot yield the right check value, so a mistake
 * shows up as a failing test rather than as a tool that quietly disagrees with
 * `gzip`.
 *
 * `aliases` matter more here than anywhere else in the app. Almost nobody looks for
 * "CRC-32/ISO-HDLC" — they look for "CRC-32", or "crc32", or the one PNG uses. The
 * catalogue's canonical names are precise and unfamiliar, so the search terms people
 * actually type have to be attached to them.
 */

/**
 * Widths 3 to 7 -- the fifteen models whose register is narrower than a byte.
 *
 * These check 5-bit fields inside protocol headers rather than files: CRC-5/USB guards a USB token
 * packet, CRC-7/MMC an SD card command, CRC-6/G-704 a telecom frame. They go through the
 * bit-at-a-time engine in `./engine.ts`, because a byte-indexed table cannot exist when the index is
 * wider than the register -- and they have no lookup table in the app for the same reason.
 *
 * Parsed out of the fetched RevEng page by script rather than typed, like every other table in this
 * repo that came from a document. Each carries the catalogue's own check value, and
 * `tests/crc.test.ts` asserts all fifteen.
 */
