const BY_NAME = new Map(CRC_CATALOGUE.map((m) => [m.name, m]));

export function getCrcModel(name: string): CrcModel | undefined {
  return BY_NAME.get(name);
}

export function requireCrcModel(name: string): CrcModel {
  const model = BY_NAME.get(name);
  if (!model) throw new Error(`Unknown CRC model: ${name}`);
  return model;
}

/** Grouped by width, for a sidebar or a model dropdown. */
export function crcModelsByWidth(): Map<number, CrcModel[]> {
  const groups = new Map<number, CrcModel[]>();
  for (const model of CRC_CATALOGUE) {
    const list = groups.get(model.width) ?? [];
    list.push(model);
    groups.set(model.width, list);
  }
  return groups;
}
