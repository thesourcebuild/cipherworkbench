/**
 * The four L-box tables the LS-designs need, parsed out of the reference by script.
 *
 * An LS-design *is* a pair of tables, so these are not an implementation detail -- they are the cipher.
 * Robin and Robin* share one pair (which is an involution, and is what makes Robin its own inverse) and
 * Fantomas has the other. Each pair encodes one 16-by-16 binary matrix as two byte-indexed halves:
 * `v -> high[v >> 8] ^ low[v & 0xff]`.
 *
 * They live in their own module because `ls-designs.ts` is otherwise short enough to read in one sitting,
 * and 1 KB of literal in the middle of it would bury the three-line difference between Robin and Robin*.
 * The inverses are **not** here: they are derived in `ls-designs.ts` by Gaussian elimination and checked
 * against the reference in the tests.
 */

