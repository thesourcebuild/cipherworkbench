export function pearsonHash(data: Uint8Array, outLen = 1): Uint8Array {
  const result = new Uint8Array(outLen);
  for (let j = 0; j < outLen; j++) {
    // Each destination byte uses an initial offset
    let h = (data.length > 0 ? (data[0]! + j) % 256 : j) & 0xff;
    h = PEARSON_TABLE[h]!;
    for (let i = 0; i < data.length; i++) {
      h = PEARSON_TABLE[h ^ data[i]!]!;
    }
    result[j] = h;
  }
  return result;
}
