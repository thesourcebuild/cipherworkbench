/**
 * Every AEGIS test vector in draft-irtf-cfrg-aegis-aead-18, appendix A.
 *
 * Extracted from the draft's text by script -- the wrapped hex continuation lines are exactly the
 * thing to get wrong by hand. Four of the nine vectors per variant are deliberately *invalid*: the
 * draft supplies them so an implementation can prove it rejects a wrong key, a flipped ciphertext
 * bit, altered associated data and a corrupted tag. `invalid: true` marks those.
 *
 * The state-update vectors are here too. They are the only thing that isolates the update function
 * from the sponge around it, which matters because AEGIS's two variants have different update
 * functions and a mix-up would otherwise surface only as a wrong tag.
 */

export interface AegisVector {
  /** The draft's own section label, so a failure names the vector. */
  label: string;
  key: string;
  nonce: string;
  ad: string;
  /** Absent for the invalid vectors, which supply only a ciphertext to reject. */
  msg: string | null;
  ct: string;
  tag128: string;
  tag256: string;
  invalid: boolean;
}

export interface AegisUpdateVector {
  before: readonly string[];
  /** One block for AEGIS-256, two for AEGIS-128L. */
  m: readonly string[];
  after: readonly string[];
}

