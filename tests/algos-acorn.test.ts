describe("ACORN-128 v3", () => {
  it("reproduces every published ciphertext and tag, in both directions", () => {
    expect(VECTORS).toHaveLength(4);
    for (const v of VECTORS) {
      const sealed = acornEncrypt(
        unhex(v.key),
        unhex(v.nonce),
        unhex(v.plaintext),
        unhex(v.ad),
      );
      expect(hex(sealed.subarray(0, v.plaintext.length / 2)), `${v.name} ciphertext`).toBe(
        v.ciphertext,
      );
      expect(hex(sealed.subarray(v.plaintext.length / 2)), `${v.name} tag`).toBe(v.tag);

      // Against the published ciphertext, not a re-encryption of ours.
      const opened = acornDecrypt(
        unhex(v.key),
        unhex(v.nonce),
        unhex(v.ciphertext + v.tag),
        unhex(v.ad),
      );
      expect(hex(opened), `${v.name} decrypt`).toBe(v.plaintext);
    }
  });

  it("reproduces the state after initialisation and after the associated data", () => {
    /**
     * The assertions that make a failure above diagnosable rather than just red. Initialisation is
     * 1,792 steps of the same function the rest of the cipher uses, so a state that matches here rules
     * out the taps, the bit order and the key load in one line -- which is exactly how the separator
     * bug was found.
     */
    for (const v of VECTORS) {
      const states = acornPhaseStates(unhex(v.key), unhex(v.nonce), unhex(v.ad));
      expect(hex(states.afterInit), `${v.name} after init`).toBe(v.afterInit);
      expect(hex(states.afterAd), `${v.name} after associated data`).toBe(v.afterAd);
    }
  });

  it("separates the two paddings, which differ only in one control bit", () => {
    /**
     * The separator after the associated data runs with `cb = 1` and the one after the message with
     * `cb = 0`. So the same bytes as associated data and as message must give different tags -- and a
     * mode that used one constant for both would accept an attacker moving bytes across that boundary,
     * which no round trip can see.
     */
    const key = unhex("00112233445566778899aabbccddeeff");
    const nonce = new Uint8Array(16);
    const block = new Uint8Array(8).fill(0x5a);
    const asAd = acornEncrypt(key, nonce, new Uint8Array(0), block);
    const asMessage = acornEncrypt(key, nonce, block, new Uint8Array(0));
    expect(hex(asAd)).not.toBe(hex(asMessage.subarray(8)));
  });

  it("refuses a tag that has been touched, byte by byte", () => {
    const key = unhex("00112233445566778899aabbccddeeff");
    const nonce = new Uint8Array(16);
    const message = Uint8Array.from({ length: 40 }, (_, i) => (i * 7 + 3) & 0xff);
    const ad = Uint8Array.from({ length: 5 }, (_, i) => i);
    const sealed = acornEncrypt(key, nonce, message, ad);
    expect(hex(acornDecrypt(key, nonce, sealed, ad))).toBe(hex(message));

    for (let i = 0; i < 16; i++) {
      const damaged = Uint8Array.from(sealed);
      damaged[sealed.length - 16 + i] = damaged[sealed.length - 16 + i]! ^ 1;
      expect(() => acornDecrypt(key, nonce, damaged, ad), `tag byte ${i}`).toThrow(
        /does not match/,
      );
    }
    const otherAd = Uint8Array.from(ad);
    otherAd[0] = otherAd[0]! ^ 1;
    expect(() => acornDecrypt(key, nonce, sealed, otherAd)).toThrow(/does not match/);
  });

  it("refuses a key, nonce or sealed message of the wrong length", () => {
    expect(() => acornEncrypt(new Uint8Array(32), new Uint8Array(16), new Uint8Array(0))).toThrow(
      /exactly 16 bytes/,
    );
    expect(() => acornEncrypt(new Uint8Array(16), new Uint8Array(12), new Uint8Array(0))).toThrow(
      /exactly 16 bytes/,
    );
    expect(() => acornDecrypt(new Uint8Array(16), new Uint8Array(16), new Uint8Array(4))).toThrow(
      /at least 16 bytes/,
    );
  });
});
