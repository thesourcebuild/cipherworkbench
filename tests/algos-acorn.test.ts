/**
 * ACORN-128 v3 -- a CAESAR portfolio cipher, and the smallest AEAD in this repo.
 *
 * No oracle. What stands behind it is the four vector sets in FELICS's
 * `authenticated_ciphers/source/ciphers/ACORN_1_128_128_293_128_v01/source/test_vectors.c`, and the
 * shape of those fixtures is the point: each one carries **the state after every phase** as well as
 * the ciphertext and tag.
 *
 * That is a materially better fixture than a ciphertext alone, and it earned itself here. The first
 * attempt got all four wrong, and the post-initialisation state matched *exactly* -- which said in one
 * comparison that the step function, the tap positions, the bit order and the 1,792-step key load were
 * all correct and the fault was in a later phase. It was the separator: 256 steps, and I had written
 * 384. A fixture with only ciphertext would have left the whole implementation as the search space.
 *
 * So both intermediate states are asserted here rather than only used for debugging. If a future edit
 * breaks the separator again, the initialisation assertion passing is the message.
 *
 * The four sets between them cover an all-zero key and nonce, a patterned key, associated data at
 * exactly one block and at seven bytes, and messages of 4, 16 and 17 bytes -- so both the byte-aligned
 * and the short cases of each phase are reached. Two of the four are commented out in the source file
 * (FELICS keeps one live at a time via `#if TEST`), which is why they are extracted rather than read
 * off the active arm.
 *
 * **The table below was generated by script from that file, not transcribed.** Hand-copying it went
 * wrong on the first attempt -- `71e8` written as `718e` in one tag, which is a plausible-looking value
 * that fails one assertion and tells you nothing. Same rule as every other fixture here.
 */
import { describe, expect, it } from "vitest";
import { acornDecrypt, acornEncrypt, acornPhaseStates } from "@ocs/algos";

const unhex = (text: string): Uint8Array =>
  text === "" ? new Uint8Array(0) : Uint8Array.from(text.match(/../g)!.map((p) => parseInt(p, 16)));
const hex = (bytes: Uint8Array): string =>
  [...bytes].map((b) => b.toString(16).padStart(2, "0")).join("");

interface AcornVector {
  readonly name: string;
  readonly key: string;
  readonly nonce: string;
  readonly ad: string;
  readonly plaintext: string;
  readonly ciphertext: string;
  readonly tag: string;
  /** The 293-bit state packed into 37 bytes, least significant bit first. */
  readonly afterInit: string;
  readonly afterAd: string;
}

